"""Summarise the downloaded dataset into docs/dataset.md. These are the numbers you quote.

Run from the project root:
    python -m sectra.ingestion.dataset_report
"""

from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def xbrl_stats(path: Path) -> dict:
    """raw = every fact row; framed = facts SEC assigned to one calendar period (duplicates removed)."""
    data = json.loads(path.read_text())
    raw = framed = concepts = 0
    for tags in data.get("facts", {}).values():  # taxonomies: dei, us-gaap, ifrs-full, srt...
        for body in tags.values():
            concepts += 1
            for facts in body.get("units", {}).values():
                raw += len(facts)
                framed += sum(1 for f in facts if "frame" in f)
    return {"raw": raw, "framed": framed, "concepts": concepts}


def read_csv(path: Path) -> list[dict]:
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def build_report(root: Path) -> str:
    manifest = root / "data" / "raw" / "manifest"
    companies = read_csv(manifest / "companies.csv")
    filings = read_csv(manifest / "filings.csv")
    run = json.loads((manifest / "last_run.json").read_text())

    by_ticker = defaultdict(list)
    for f in filings:
        by_ticker[f["ticker"]].append(f)
    sectors = Counter(c["sector"] for c in companies)
    total_mb = sum(int(f["size_bytes"]) for f in filings) / 1e6
    periods = sorted(f["period_of_report"] for f in filings)

    xbrl_total = Counter()
    per_company = []
    for c in companies:
        path = root / "data" / "raw" / "xbrl" / f"CIK{c['cik']}.json"
        stats = xbrl_stats(path) if path.exists() else {"raw": 0, "framed": 0, "concepts": 0}
        xbrl_total.update(stats)
        fs = sorted(f["period_of_report"] for f in by_ticker[c["ticker"]])
        per_company.append((c, len(fs), f"{fs[0]} to {fs[-1]}" if fs else "-", stats))

    lines = [
        "# Dataset",
        "",
        f"Snapshot of SEC EDGAR taken {run['run_at_utc']} (UTC). Generated by `python -m sectra.ingestion.dataset_report`.",
        "",
        "| | |",
        "|---|---|",
        f"| Companies | {len(companies)} across {len(sectors)} sectors ({', '.join(f'{s} {n}' for s, n in sorted(sectors.items()))}) |",
        f"| Filings | {len(filings)} ({', '.join(f'{n} {k}' for k, n in Counter(f['form_type'] for f in filings).items())}) |",
        f"| Periods covered | {periods[0] if periods else '-'} to {periods[-1] if periods else '-'} |",
        f"| Filing documents | {total_mb:,.0f} MB of HTML |",
        f"| XBRL fact rows (raw) | {xbrl_total['raw']:,} |",
        f"| XBRL facts after SEC frame dedup | {xbrl_total['framed']:,} |",
        f"| Distinct XBRL concepts | {xbrl_total['concepts']:,} |",
        "",
        "Raw fact rows count the same value each time it is re-reported in a later filing;",
        "the frame count keeps one fact per company, concept, unit and calendar period.",
        "",
        "## By company",
        "",
        "| Ticker | Name | Sector | Filings | Periods | XBRL facts (raw) | XBRL facts (dedup) |",
        "|---|---|---|---|---|---|---|",
    ]
    for c, n, span, s in per_company:
        lines.append(f"| {c['ticker']} | {c['name']} | {c['sector']} | {n} | {span} | {s['raw']:,} | {s['framed']:,} |")
    if run.get("failures"):
        lines += ["", "## Failures in last run", ""] + [f"- {t}: {e}" for t, e in run["failures"].items()]
    return "\n".join(lines) + "\n"


def main() -> None:
    report = build_report(ROOT)
    out = ROOT / "docs" / "dataset.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report)
    print(report)
    print(f"Written to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()